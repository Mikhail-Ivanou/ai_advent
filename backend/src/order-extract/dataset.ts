// Day 29: control e-mails with the expected order. Nine short ones test the
// extraction rules (phone formats, relative dates, corrections, quantities in
// words, the payment kind, urgency); three long ones (≈5k tokens with the
// prompt) put the new order at the top of a long letter — the case a small
// context window breaks: Ollama drops the beginning of a prompt that doesn't
// fit, so the model sees the tail (old history) without the instructions.

export interface ExpectedOrder {
  /** Surname — the customer field must contain it. */
  customer: string;
  phone: string;
  city: string;
  /** sku -> qty, the final composition. */
  items: Record<string, number>;
  delivery_date: string | null;
  payment: 'card' | 'cash' | 'invoice';
  urgent: boolean;
}

export interface OrderEmail {
  id: string;
  /** What this e-mail checks. */
  about: string;
  date: string;
  text: string;
  expected: ExpectedOrder;
}

