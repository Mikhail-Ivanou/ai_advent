const LEGAL =
  'Это письмо и все вложения конфиденциальны и предназначены только для указанного адресата. Если вы получили его по ошибке, сообщите отправителю и удалите письмо. Мнения, изложенные в письме, принадлежат автору и могут не совпадать с позицией компании.';

function quotedThread(count: number): string {
  const parts: string[] = [];
  for (let i = 0; i < count; i++) {
    const n = 48200 + i * 7;
    const day = String(1 + (i % 28)).padStart(2, '0');
    parts.push(
      `> ${i % 2 ? 'Служба поддержки' : 'Тимур Хасанов'}, ${day}.0${1 + (i % 9)}.2026:`,
      ...OLD_STATUS[i % OLD_STATUS.length](n)
        .split('. ')
        .map((s) => `> ${s.trim()}${s.endsWith('.') ? '' : '.'}`),
      `> ${LEGAL}`,
      '>',
    );
  }
  return parts.join('\n');
}

