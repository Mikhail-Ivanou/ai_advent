function internalThread(count: number): string {
  return Array.from({ length: count }, (_, i) => {
    const who = ['Ольга (склад)', 'Игорь (логистика)', 'Марина (продажи)'][i % 3];
    return `>> ${who}:\n>> ${INTERNAL[i % INTERNAL.length]}\n>> ${LEGAL}`;
  }).join('\n>>\n');
}

